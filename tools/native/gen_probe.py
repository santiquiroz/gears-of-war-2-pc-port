"""Writes tools/native/probe_hooks.inc from pm4_scan.py's JSON: one PROBE(name, index, opcodes) line per
function that builds PM4 headers, for the counting hooks of tools/native/native_probe.cpp.

  python tools/native/gen_probe.py out/native/pm4_scan.json
"""
import json
import os
import sys


def main():
    scan = json.load(open(sys.argv[1], encoding="utf-8"))
    out = os.path.join(os.path.dirname(os.path.abspath(__file__)), "probe_hooks.inc")
    lines = ["// Generated by tools/native/gen_probe.py from pm4_scan.py; do not edit."]
    for index, (name, opcodes) in enumerate(sorted(scan.items())):
        label = " ".join(sorted(opcodes))
        lines.append(f'PROBE({name}, {index}, "{label}")')
    with open(out, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines) + "\n")
    print(f"{len(scan)} functions -> {out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
